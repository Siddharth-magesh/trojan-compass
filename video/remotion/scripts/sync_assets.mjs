// Reads video/asset_manifest.json, checks which asset files exist in public/ (video duration via ffprobe), writes
// src/config/available_assets.json for the compositions and regenerates video/missing_assets.md. Run before preview/render.
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const manifest = JSON.parse(readFileSync(path.join(ROOT, '..', 'asset_manifest.json'), 'utf8')).assets;
const available = {};
const missing = [];

for (const asset of manifest) {
  if (!asset.file) continue;
  const full = path.join(ROOT, 'public', asset.file);
  if (!existsSync(full)) {
    missing.push(asset);
    continue;
  }
  const entry = { file: asset.file };
  if (/\.(mp4|webm|mov)$/.test(asset.file)) {
    const out = execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', full]).toString();
    entry.duration_s = Math.round(parseFloat(out) * 100) / 100;
  }
  // JSON assets (facts we supply) are embedded so compositions never import a file that may not exist.
  if (asset.file.endsWith('.json')) entry.data = JSON.parse(readFileSync(full, 'utf8'));
  available[asset.id] = entry;
}

writeFileSync(path.join(ROOT, 'src', 'config', 'available_assets.json'), JSON.stringify(available, null, 1) + '\n');

const rows = missing.map((a) => `| ${a.id} | ${a.scene} | ${a.time} | ${a.status} | \`${a.file}\` | ${a.shows} |`);
writeFileSync(path.join(ROOT, '..', 'missing_assets.md'), [
  '<!-- Generated by video/remotion/scripts/sync_assets.mjs from asset_manifest.json. Do not edit by hand. -->',
  '# Missing assets',
  '',
  missing.length ? 'Each missing asset renders as a marked placeholder until its file exists.' : 'All assets are present.',
  '',
  '| ID | Scene | Time | Status | Expected file (under video/remotion/public/) | What it must show |',
  '|---|---|---|---|---|---|',
  ...rows,
  '',
].join('\n'));
console.log(`available: ${Object.keys(available).join(', ') || 'none'}`);
console.log(`missing: ${missing.map((a) => a.id).join(', ') || 'none'}`);
